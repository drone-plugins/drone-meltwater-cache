const berryLock = "# This file is generated by running \"yarn install\" inside your project.\n" +
	"# Manual changes might be lost - proceed with caution!\n\n" +
	"__metadata:\n  version: 8\n  cacheKey: 10c0\n"

func TestIsYarnBerry(t *testing.T) {
	for _, tc := range []struct {
		name  string
		files map[string]string
		berry bool
	}{
		{"classicLock", map[string]string{"yarn.lock": "# yarn lockfile v1\n"}, false},
		{"berryLock", map[string]string{"yarn.lock": berryLock}, true},
		{"yarnrcYml", map[string]string{"yarn.lock": "x", ".yarnrc.yml": "nodeLinker: node-modules\n"}, true},
		{"packageManager4", map[string]string{"yarn.lock": "x", "package.json": `{"packageManager":"yarn@4.9.1"}`}, true},
		{"packageManager1", map[string]string{"yarn.lock": "x", "package.json": `{"packageManager":"yarn@1.22.22"}`}, false},
		{"packageManagerPnpm", map[string]string{"yarn.lock": "x", "package.json": `{"packageManager":"pnpm@10.0.0"}`}, false},
		{"invalidPackageJSON", map[string]string{"yarn.lock": "x", "package.json": "{"}, false},
		{"legacyYamlName", map[string]string{"yarn.lock": "x", ".yarnrc.yaml": "cacheFolder: x\n"}, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			root := jsWorkspace(t)
			for name, content := range tc.files {
				cargoWrite(t, name, content)
			}
			test.Equals(t, tc.berry, isYarnBerry(root))
		})
	}
}

func Test_yarnPreparer_BerryCacheResolution(t *testing.T) {
	for _, tc := range []struct {
		name, env, rc, cache, state string
	}{
		{name: "default", cache: ".yarn/cache", state: ".yarn/install-state.gz"},
		{name: "rcCacheFolder", rc: "cacheFolder: ./custom-cache\n", cache: "custom-cache", state: ".yarn/install-state.gz"},
		{name: "envBeatsRc", env: "env-cache", rc: "cacheFolder: ./custom-cache\n", cache: "env-cache", state: ".yarn/install-state.gz"},
		{name: "rcInstallState", rc: "installStatePath: 'state/install.gz'\n", cache: ".yarn/cache", state: "state/install.gz"},
		{name: "rcGlobalCacheIgnored", rc: "enableGlobalCache: true\n", cache: ".yarn/cache", state: ".yarn/install-state.gz"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			root := jsWorkspace(t)
			t.Setenv("YARN_CACHE_FOLDER", tc.env)
			cargoWrite(t, "yarn.lock", berryLock)
			if tc.rc != "" {
				cargoWrite(t, yarnBerryRCFileName, tc.rc)
			}

			cache, err := newYarnPreparer().PrepareRepo(root)
			test.Ok(t, err)
			test.Equals(t, filepath.Join(root, tc.cache), cache)
			extra, err := yarnCacheDirs(root)
			test.Ok(t, err)
			test.Equals(t, []string{filepath.Join(root, "node_modules"), filepath.Join(root, tc.state)}, extra)
		})
	}
}

func Test_yarnPreparer_BerryWritesNothing(t *testing.T) {
	root := jsWorkspace(t)
	rc := "nodeLinker: node-modules\ncacheFolder: ./.yarn/cache\n"
	cargoWrite(t, "yarn.lock", berryLock)
	cargoWrite(t, yarnBerryRCFileName, rc)

	for i := 0; i < 2; i++ {
		_, err := newYarnPreparer().PrepareRepo(root)
		test.Ok(t, err)
	}

	got, err := os.ReadFile(yarnBerryRCFileName)
	test.Ok(t, err)
	test.Equals(t, rc, string(got))
	for _, name := range []string{".yarnrc", ".yarnrc.yaml"} {
		_, err := os.Stat(name)
		test.Assert(t, os.IsNotExist(err), "berry preparer must not create %s", name)
	}
}

// Zero-install repos commit their packages to .yarn/cache; the cache step has
// to read from the same folder instead of redirecting Yarn elsewhere.
func Test_yarnPreparer_BerryZeroInstall(t *testing.T) {
	root := jsWorkspace(t)
	cargoWrite(t, "yarn.lock", berryLock)
	cargoWrite(t, ".yarn/cache/is-odd-npm-3.0.1-abc.zip", "zip")
	cargoWrite(t, ".yarn/releases/yarn-4.9.1.cjs", "release")

	dirs, tools, _, err := DetectDirectoriesToCache(false)
	test.Ok(t, err)
	test.Equals(t, []string{toolYarn}, tools)
	test.Equals(t, []string{
		filepath.Join(root, ".yarn", "cache"),
		filepath.Join(root, "node_modules"),
		filepath.Join(root, ".yarn", "install-state.gz"),
	}, dirs)
}

func Test_yarnPreparer_ClassicUnchanged(t *testing.T) {
	root := jsWorkspace(t)
	cargoWrite(t, "yarn.lock", "# yarn lockfile v1\n")

	cache, err := newYarnPreparer().PrepareRepo(root)
	test.Ok(t, err)
	test.Equals(t, filepath.Join(root, ".yarn"), cache)
	got, err := os.ReadFile(".yarnrc")
	test.Ok(t, err)
	test.Equals(t, fmt.Sprintf("\n--cache-folder %s\n", filepath.Join(root, ".yarn")), string(got))
	_, err = os.Stat(".yarnrc.yaml")
	test.Assert(t, os.IsNotExist(err), "classic preparer must not create .yarnrc.yaml")

	extra, err := yarnCacheDirs(root)
	test.Ok(t, err)
	test.Equals(t, []string{filepath.Join(root, "node_modules")}, extra)
}

func TestScenario_YarnBerry_Keys(t *testing.T) {
	jsWorkspace(t)
	cargoWrite(t, "package.json", `{"packageManager":"yarn@4.9.1"}`)
	cargoWrite(t, "yarn.lock", berryLock)
	_, tools, first, err := DetectDirectoriesToCache(false)
	test.Ok(t, err)
	test.Equals(t, []string{toolYarn}, tools)
	test.Equals(t, fmt.Sprintf("%x%x", md5.Sum([]byte(`{"packageManager":"yarn@4.9.1"}`)), md5.Sum([]byte(berryLock))), first)

	cargoWrite(t, yarnBerryRCFileName, "nodeLinker: node-modules\n")
	_, _, same, err := DetectDirectoriesToCache(false)
	test.Ok(t, err)
	test.Equals(t, first, same)

	cargoWrite(t, "yarn.lock", berryLock+"\n\"is-odd@npm:3.0.1\":\n  version: 3.0.1\n")
	_, _, changed, err := DetectDirectoriesToCache(false)
	test.Ok(t, err)
	test.Assert(t, first != changed, "lockfile must invalidate the key")
}
